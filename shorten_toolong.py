def shorten(jp, zh, budget):
    for a, b in sorted({**RULES, **OVERRIDE}.items(), key=lambda x: -len(x[0])):
        if len(strip(zh)) <= budget:
            break
        if a in zh:
            zh = zh.replace(a, b)
    return zh


def main():
    dry = '--dry' in sys.argv
    d = json.load(open('out/field_toolong.json', encoding='utf-8'))
    byjp = {}
    for e in d:
        byjp.setdefault(e['jp'], e)
    fixed, still = {}, []
    for e in byjp.values():
        zh = shorten(e['jp'], e['oldzh'], e['budget'])
        if len(strip(zh)) <= e['budget']:
            fixed[e['jp']] = zh
        else:
            still.append(e)
    print(f'唯一 {len(byjp)}: 缩好 {len(fixed)}, 还超 {len(still)}')
    if still:
        print('还超样本(b=budget, 现长):')
        for e in sorted(still, key=lambda x: len(strip(x['oldzh'])) - x['budget'])[:30]:
            z = shorten(e['jp'], e['oldzh'], e['budget'])
            print(f"  b{e['budget']} 现{len(strip(z))} jp={strip(e['jp'])[:22]!r} zh={strip(z)[:26]!r}")
    if dry:
        return
    # 合回 field_text_zh.json（按 jp 匹配, 所有出现位置更新）
    fz = json.loads(open('out/field_text_zh.json', encoding='utf-8').read())
    n = 0
    for it in fz:
        if it['jp'] in fixed and fixed[it['jp']] != it.get('zh'):
            it['zh'] = fixed[it['jp']]; n += 1
    json.dump(fz, open('out/field_text_zh.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print(f'合回 {n} 条 → out/field_text_zh.json')


if __name__ == '__main__':
    main()
